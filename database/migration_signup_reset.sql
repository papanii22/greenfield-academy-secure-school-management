ALTER TABLE users
    ADD COLUMN IF NOT EXISTS auth_version BIGINT NOT NULL DEFAULT 1;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'users_auth_version_nonnegative'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_auth_version_nonnegative
            CHECK (auth_version >= 0);
    END IF;
END
$$;

ALTER TABLE audit_logs
    ADD COLUMN IF NOT EXISTS target_user_id BIGINT REFERENCES users(id);

CREATE TABLE IF NOT EXISTS signup_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMPTZ,
    reviewed_by BIGINT REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS signup_requests_pending_idx
    ON signup_requests (requested_at, id)
    WHERE status = 'pending';

CREATE TABLE IF NOT EXISTS password_reset_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(12) NOT NULL DEFAULT 'open'
        CHECK (status IN ('open', 'completed')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    completed_by BIGINT REFERENCES users(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS password_reset_requests_one_open_per_user_idx
    ON password_reset_requests (user_id)
    WHERE status = 'open';

CREATE INDEX IF NOT EXISTS password_reset_requests_open_idx
    ON password_reset_requests (requested_at, id)
    WHERE status = 'open';

CREATE TABLE IF NOT EXISTS login_failure_hints (
    email_normalized VARCHAR(254) NOT NULL,
    ip_address VARCHAR(45) NOT NULL,
    failures INTEGER NOT NULL DEFAULT 0 CHECK (failures >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (email_normalized, ip_address)
);
