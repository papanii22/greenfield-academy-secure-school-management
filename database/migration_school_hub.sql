-- School hub features: profiles, notices, calendar, library, messages,
-- finance, assignments and personal tasks. Safe to run more than once.
-- Run after schema.sql and migration_signup_reset.sql.

CREATE TABLE IF NOT EXISTS user_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    phone VARCHAR(30),
    address VARCHAR(200),
    date_of_birth DATE,
    gender VARCHAR(10) CHECK (gender IN ('female', 'male')),
    bio VARCHAR(500),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    body TEXT NOT NULL CHECK (char_length(body) <= 5000),
    audience VARCHAR(10) NOT NULL DEFAULT 'all'
        CHECK (audience IN ('all', 'teachers', 'students')),
    tags VARCHAR(120) NOT NULL DEFAULT '',
    author_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS notices_created_at_idx ON notices (created_at DESC);

CREATE TABLE IF NOT EXISTS notice_views (
    notice_id BIGINT NOT NULL REFERENCES notices(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    viewed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (notice_id, user_id)
);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(500) NOT NULL DEFAULT '',
    event_date DATE NOT NULL,
    start_time TIME,
    end_time TIME,
    category VARCHAR(12) NOT NULL DEFAULT 'event'
        CHECK (category IN ('event', 'meeting', 'exam', 'holiday')),
    audience VARCHAR(10) NOT NULL DEFAULT 'all'
        CHECK (audience IN ('all', 'teachers', 'students')),
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT events_time_order CHECK (
        start_time IS NULL OR end_time IS NULL OR end_time >= start_time
    )
);

CREATE INDEX IF NOT EXISTS events_date_idx ON events (event_date);

CREATE TABLE IF NOT EXISTS books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    title VARCHAR(200) NOT NULL,
    author VARCHAR(120) NOT NULL,
    subject VARCHAR(100) NOT NULL,
    classes VARCHAR(60) NOT NULL DEFAULT '',
    publish_year SMALLINT CHECK (publish_year BETWEEN 1400 AND 2100),
    status VARCHAR(12) NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'checked_out')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100),
    is_group BOOLEAN NOT NULL DEFAULT FALSE,
    description VARCHAR(300) NOT NULL DEFAULT '',
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conversation_members (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_read_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (conversation_id, user_id)
);

CREATE INDEX IF NOT EXISTS conversation_members_user_idx
    ON conversation_members (user_id);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id),
    body VARCHAR(2000) NOT NULL CHECK (char_length(btrim(body)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS messages_conversation_idx
    ON messages (conversation_id, created_at DESC);

CREATE TABLE IF NOT EXISTS fee_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    term SMALLINT NOT NULL CHECK (term IN (1, 2, 3)),
    tuition_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (tuition_fee >= 0),
    activities_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (activities_fee >= 0),
    misc_fee NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (misc_fee >= 0),
    amount_paid NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    due_date DATE NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fee_records_student_term_unique UNIQUE (student_id, term),
    CONSTRAINT fee_records_not_overpaid
        CHECK (amount_paid <= tuition_fee + activities_fee + misc_fee)
);

CREATE TABLE IF NOT EXISTS fee_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_id BIGINT NOT NULL REFERENCES fee_records(id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    paid_on DATE NOT NULL,
    recorded_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS fee_payments_paid_on_idx ON fee_payments (paid_on);

CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(60) NOT NULL,
    description VARCHAR(150) NOT NULL,
    quantity VARCHAR(40) NOT NULL DEFAULT '',
    amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
    paid_on DATE NOT NULL,
    recorded_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS expenses_paid_on_idx ON expenses (paid_on);

CREATE TABLE IF NOT EXISTS assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(id),
    class_id BIGINT NOT NULL REFERENCES classes(id),
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    title VARCHAR(150) NOT NULL,
    description VARCHAR(1000) NOT NULL DEFAULT '',
    due_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS assignments_class_idx ON assignments (class_id, due_at);

CREATE TABLE IF NOT EXISTS assignment_submissions (
    assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES students(id),
    status VARCHAR(12) NOT NULL DEFAULT 'not_started'
        CHECK (status IN ('not_started', 'in_progress', 'submitted', 'reviewed')),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (assignment_id, student_id)
);

CREATE TABLE IF NOT EXISTS user_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    due_date DATE,
    done BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS user_tasks_user_idx ON user_tasks (user_id, done, due_date);
